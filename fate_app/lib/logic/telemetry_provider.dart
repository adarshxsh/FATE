  // ══════════════════════════════════════════════════════════════════════
  // SCORING
  // ══════════════════════════════════════════════════════════════════════

  Future<void> _recalculateLocalScore() async {
    // Refresh app usage from OS before scoring so digital score is accurate
    await _refreshAppUsageFromOS();
    final scores = await ScoringEngine.calculateDailyCas(DateTime.now());
    _focusScore = scores['CAS'] ?? 50.0;
    _sLoc = scores['S_loc'] ?? 0.0;
    _sSoc = scores['S_soc'] ?? 0.0;
    _sDig = scores['S_dig'] ?? 0.0;
    notifyListeners();
  }

  // ══════════════════════════════════════════════════════════════════════
  // ANDROID EVENT BUS
  // ══════════════════════════════════════════════════════════════════════

  void _listenToEvents() {
    _eventChannel.receiveBroadcastStream().listen((dynamic event) {
      final Map<dynamic, dynamic> map = event as Map<dynamic, dynamic>;
      final String type = map['type'] as String;
      final Map<dynamic, dynamic> data = map['data'] as Map<dynamic, dynamic>;

      debugPrint('EventBus received: $type');

      switch (type) {
        case 'notification_posted':
          _fragmentationScore = (_fragmentationScore + 0.05).clamp(0.0, 1.0);
          final notifPkg = data['package'] ?? 'unknown';
          final postTimeMs =
              data['post_time'] ?? DateTime.now().millisecondsSinceEpoch;
          _pendingNotifications[notifPkg] = {
            'postTimeMs': postTimeMs,
            'title': data['title'] ?? '',
            'text': data['text'] ?? '',
          };
          _notificationLog.insert(0, {
            'package': notifPkg,
            'title': data['title'] ?? '',
            'text': data['text'] ?? '',
            'time': DateTime.now().toIso8601String(),
            'status': 'pending',
          });
          if (_notificationLog.length > 50) {
            _notificationLog.removeRange(50, _notificationLog.length);
          }
          _addLog('NOTIF_RECV | From: $notifPkg | ${data['title']}');
          _cleanExpiredNotifications();
          notifyListeners();
          break;

        case 'notification_removed':
          final removedPkg = data['package'] ?? 'unknown';

          if (_pendingNotifications.containsKey(removedPkg)) {
            final notifData = _pendingNotifications.remove(removedPkg)!;
            final content = '${notifData['title']} ${notifData['text']}';
            _db.insertNotificationLog({
              'app_category': 'OTHER',
              'content': content,
              'response_time_seconds': null, // null means dismissed
            });
          }

          for (final entry in _notificationLog) {
            if (entry['package'] == removedPkg &&
                entry['status'] == 'pending') {
              entry['status'] = 'dismissed';
              break;
            }
          }
          _addLog('NOTIF_DISMISS | $removedPkg dismissed');
          notifyListeners();
          break;

        case 'location_update':
          _lastLat = (data['lat'] as num).toDouble();
          _lastLng = (data['lng'] as num).toDouble();
          final newLat = _lastLat!;
          final newLng = _lastLng!;
          final newZone = _detectZoneLocally(newLat, newLng);

          if (_currentZone == null) {
            _currentZone = newZone;
            _periodsInCurrentZone = 1;
          } else if (newZone == _currentZone) {
            _periodsInCurrentZone++;
          } else {
            _pendingLocationUpdates.add({
              'lat': newLat,
              'lng': newLng,
              'zone': _currentZone,
              'periods_count': _periodsInCurrentZone,
            });
            _currentZone = newZone;
            _periodsInCurrentZone = 1;
          }

          _db.insertLocationLog({
            'lat': newLat,
            'lng': newLng,
            'zone': _currentZone,
            'periods_count': _periodsInCurrentZone,
          });
          _currentContext = newZone;
          _addLog('LOC_SECURE | Saved to vault | Zone: $newZone');
          _recalculateLocalScore();
          notifyListeners();
          break;

        case 'peer_found':
          final endpointId = data['endpointId'] ?? 'unknown_id';
          final rawName = data['name'] ?? 'Unknown';
          // Distance comes from BLE RSSI (ble_rssi events), if we already
          // have a fresh reading for this peer.

          // P2P: BLE payload format is "<bleId>|<deviceModel>"
          String peerBleId = rawName;
          String fallbackDeviceName = 'Unknown Device';
          if (rawName.contains('|')) {
            final parts = rawName.split('|');
            peerBleId = parts[0];
            if (parts.length > 1) fallbackDeviceName = parts[1];
          }

          if (!_nearbyDevices.containsKey(endpointId)) {
            _nearbyPeers++;
            _peerFoundTimestamps[endpointId] = DateTime.now();
          }
          _endpointToBle[endpointId] = peerBleId;
          _nearbyDevices[endpointId] = fallbackDeviceName;
          final distance = _ranging.distanceOf(peerBleId);
          if (!_peerInfo.containsKey(peerBleId)) {
            unawaited(_lookupPeer(peerBleId));
          }
          if (distance != null) {
            _peerDistances[endpointId] = distance;
          } else {
            _peerDistances.remove(endpointId);
          }

          // Alert for unknown devices: once per peer per session, not on
          // every rediscovery.
          if (!isFriend(peerBleId) && _alertedUnknown.add(peerBleId)) {
            LocalNotificationService.showUnknownDeviceAlert(
              fallbackDeviceName,
              distance,
            );
          }

          _db.insertProximityLog({
            'nearby_peers': _nearbyPeers,
            'peer_name': fallbackDeviceName,
            'distance': distance,
          });
          _recalculateLocalScore();
          _addLog(
            'PROX | Found $peerBleId${distance != null ? " at ~${distance.toStringAsFixed(1)}m (BLE)" : " (distance pending BLE)"}',
          );
          notifyListeners();
          break;

        case 'peer_lost':
          final endpointId = data['endpointId'] ?? 'unknown_id';
          if (_nearbyDevices.containsKey(endpointId)) {
            final peerBleId = bleIdFor(endpointId);
            final foundAt = _peerFoundTimestamps[endpointId];
            if (foundAt != null) {
              final rawSeconds = DateTime.now().difference(foundAt).inSeconds;
              _peerFoundTimestamps.remove(endpointId);
              // With BLE ranging, only time spent within ~3 m is engagement
              // (Nearby discovery alone reaches tens of metres). Without any
              // RSSI data, fall back to the found→lost window.
              final close = _closeSeconds.remove(peerBleId);
              _lastRangeAt.remove(peerBleId);
              final durationSeconds = close != null
                  ? close.round()
                  : rawSeconds;
              // Friends are excluded from contagion scoring (see Social tab).
              if (durationSeconds > 60 && !isFriend(peerBleId)) {
                // peer_cas_at_time stays NULL (ignored by scoring) until the
                // server returns the peer's real CAS for this moment.
                _db
                    .insertEngagementLog({
                      'peer_device_id': endpointId,
                      'peer_ble_id': peerBleId,
                      'engagement_duration_seconds': durationSeconds.toDouble(),
                      'peer_cas_at_time': null,
                    })
                    .then((_) => syncWithCommunity());
                _addLog(
                  'ENG_SECURE | Vaulted engagement: $peerBleId | ${durationSeconds}s',
                );
              }
            }
            _endpointToBle.remove(endpointId);
            _ranging.forget(peerBleId);
            _nearbyDevices.remove(endpointId);
            _peerDistances.remove(endpointId);
            if (_nearbyPeers > 0) _nearbyPeers--;
          }
          _db.insertProximityLog({'nearby_peers': _nearbyPeers});
          _recalculateLocalScore();
          notifyListeners();
          break;

        case 'ble_rssi':
          final bleId = data['bleId'] as String?;
          final rssi = (data['rssi'] as num?)?.toInt();
          final p1m = (data['measuredPower'] as num?)?.toInt() ?? -59;
          if (bleId == null || rssi == null) break;
          final d = _ranging.addReading(bleId, rssi, p1m);
          if (d == null) break;
          // Integrate "close" time between sightings. Gaps over 5 s
          // are capped so a missed scan window doesn't count as contact.
          final now = DateTime.now();
          final prev = _lastRangeAt[bleId];
          _lastRangeAt[bleId] = now;
          _closeSeconds.putIfAbsent(bleId, () => 0.0);
          if (prev != null && d <= RssiRanging.nearMaxM) {
            final dt = now.difference(prev).inMilliseconds / 1000.0;
            _closeSeconds[bleId] = _closeSeconds[bleId]! + dt.clamp(0.0, 5.0);
          }
          var touched = false;
          _endpointToBle.forEach((endpoint, b) {
            if (b == bleId) {
              _peerDistances[endpoint] = d;
              touched = true;
            }
          });
          if (touched) notifyListeners();
          break;

        case 'app_usage':
          final pkg = data['package'] ?? 'unknown';
          double? switchTimeSecs;
          final prevApp = _lastForegroundApp;
          if (_lastForegroundApp != null && _lastForegroundApp != pkg) {
            if (_lastAppSwitchTime != null) {
              switchTimeSecs =
                  DateTime.now()
                      .difference(_lastAppSwitchTime!)
                      .inMilliseconds /
                  1000.0;
            }
            _lastAppSwitchTime = DateTime.now();
          } else if (_lastForegroundApp == null) {
            _lastAppSwitchTime = DateTime.now();
          }
          _lastForegroundApp = pkg;
          _appUsageStats[pkg] = (_appUsageStats[pkg] ?? 0) + 10;

          _db.insertDigitalLog({
            'package': pkg,
            'duration': 10000,
            'prev_package': prevApp,
            'switch_time_seconds': switchTimeSecs,
          });
          _addLog('USG_SECURE | Vaulted digital: $pkg');
          _recalculateLocalScore();

          if (_pendingNotifications.containsKey(pkg)) {
            final notifData = _pendingNotifications.remove(pkg)!;
            final postTimeMs = notifData['postTimeMs'] as int;
            final responseTimeSeconds =
                (DateTime.now().millisecondsSinceEpoch - postTimeMs) / 1000.0;
            final content = '${notifData['title']} ${notifData['text']}';
            _db.insertNotificationLog({
              'app_category': 'OTHER',
              'content': content,
              'response_time_seconds': responseTimeSeconds,
            });
            for (final entry in _notificationLog) {
              if (entry['package'] == pkg && entry['status'] == 'pending') {
                entry['status'] = 'clicked';
                entry['response_time'] = responseTimeSeconds;
                break;
              }
            }
            _addLog('NOTIF_SECURE | Vaulted interaction: $pkg');
          }
          notifyListeners();
          break;
      }
    });
  }

