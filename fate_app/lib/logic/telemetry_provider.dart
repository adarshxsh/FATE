/// Manages all device telemetry and state.
///
/// Raw telemetry is local-only (encrypted SQLite). The community server is
/// used for the parts one phone can't compute alone: a nearby peer's CAS
/// (social contagion) and campus-wide aggregates. All of it degrades to
/// local-only when offline.
///
/// Identity lifecycle:
///   1. First launch → generate local UUID + BLE advertising ID
///   2. User sets a security PIN (stored in SecureStorage via SecureDbService)
///   3. Encryption keys generated by SecureDbService (hardware-backed)
///   4. Engine starts collecting telemetry signals
class TelemetryProvider extends ChangeNotifier {
  final SharedPreferences prefs;
  final SecureDbService _db = SecureDbService();

  static const MethodChannel _channel = MethodChannel(
    'com.ate.telemetry/channel',
  );
  static const EventChannel _eventChannel = EventChannel(
    'com.ate.telemetry/events',
  );

  // ── Identity ──
  String? _localId; // UUID — stable local identity
  String? _displayName;
  String? _bluetoothId;

  // ── Core metrics ──
  double _fragmentationScore = 0.0;
  double _focusScore = 100.0;
  double _sLoc = 0.0;
  double _sSoc = 0.0;
  double _sDig = 0.0;
  String _currentContext = 'Unknown';
  int _nearbyPeers = 0;
  final Map<String, String> _nearbyDevices = {};
  final Map<String, double> _peerDistances = {};
  final Map<String, DateTime> _peerFoundTimestamps = {};
  final Set<String> _localFriends =
      {}; // Device BLE IDs marked as friends (stored locally)

  // Nearby endpointIds are ephemeral (new on every discovery); the BLE id in
  // the advertised name is the stable identity. Map one to the other.
  final Map<String, String> _endpointToBle = {};

  // BLE RSSI ranging, keyed by BLE id (see rssi_ranging.dart).
  final PeerRangingTable _ranging = PeerRangingTable();
  final Set<String> _alertedUnknown = {};
  // Seconds each peer spent within RssiRanging.nearMaxM, plus the time of
  // the last reading (to integrate between sightings).
  final Map<String, double> _closeSeconds = {};
  final Map<String, DateTime> _lastRangeAt = {};

  // ── Community (server) state ──
  final CommunityService _community = CommunityService();
  final Map<String, Map<String, dynamic>> _peerInfo =
      {}; // bleId -> {cas, display_name, known}
  Map<String, dynamic>? _campus;
  DateTime? _lastCommunitySync;
  bool _communityOnline = false;
  bool _shareZone = false;
  bool _communityEnabled = true;
  Timer? _syncTimer;
  bool _syncing = false;

  // ── Notification interaction tracking ──
  final Map<String, Map<String, dynamic>> _pendingNotifications = {};

  // ── App switch tracking ──
  String? _lastForegroundApp;
  DateTime? _lastAppSwitchTime;

  // ── Local app usage accumulation ──
  final Map<String, int> _appUsageStats = {};

  // ── Total daily usage from OS UsageStatsManager ──
  final Map<String, int> _totalDailyUsage = {};

  // ── Location tracking ──
  double? _lastLat;
  double? _lastLng;
  String? _currentZone;
  int _periodsInCurrentZone = 0;
  final List<Map<String, dynamic>> _pendingLocationUpdates = [];

  // ── Notification log for UI ──
  final List<Map<String, dynamic>> _notificationLog = [];

  // ── Permission state ──
  bool _notificationEnabled = false;
  bool _usageEnabled = false;

  // ── Weights (local only) ──
  double _spatialWeight = 0.3;
  double _socialWeight = 0.3;
  double _digitalWeight = 0.4;

  // ── Privacy audit log ──
  final List<String> _privacyLogs = [];

  // ── Security PIN state ──
  bool _isPinSet = false;
  bool _isUnlocked = true; // true by default so app doesn't lock on start

  TelemetryProvider(this.prefs) {
    _notificationEnabled = prefs.getBool('notification_enabled') ?? false;
    _usageEnabled = prefs.getBool('usage_enabled') ?? false;
    _localId = prefs.getString('local_identity_id');
    _displayName = prefs.getString('user_display_name');
    _bluetoothId = prefs.getString('bluetooth_id');
    _isPinSet = prefs.getBool('pin_is_set') ?? false;
    // We intentionally ignore any saved lock state and default to unlocked on start.
    _spatialWeight = prefs.getDouble('weight_spatial') ?? 0.3;
    _socialWeight = prefs.getDouble('weight_social') ?? 0.3;
    _digitalWeight = prefs.getDouble('weight_digital') ?? 0.4;
    _shareZone = prefs.getBool('share_zone_with_campus') ?? false;
    _communityEnabled = prefs.getBool('community_enabled') ?? true;
    _loadLocalFriends();
  }

  @override
  void dispose() {
    _syncTimer?.cancel();
    super.dispose();
  }

  // ── Getters ──
  String? get localId => _localId;
  bool get isIdentityCreated => _localId != null;
  bool get isPinSet => _isPinSet;
  bool get isUnlocked => _isUnlocked;

  /// True when the app is ready for full tracking (identity exists + PIN verified)
  bool get isReady => isIdentityCreated && (!_isPinSet || _isUnlocked);

  String? get displayName => _displayName;
  String? get bluetoothId => _bluetoothId;

  double get fragmentationScore => _fragmentationScore;
  double get focusScore => _focusScore;
  String get currentContext => _currentContext;
  int get nearbyPeers => _nearbyPeers;

  // Legacy userId compat — maps to localId hashCode for UI that expects an int
  int? get userId => _localId?.hashCode;

  List<String> get connectedPeers => _nearbyDevices.values.toList();
  Map<String, String> get nearbyDevicesMap => Map.unmodifiable(_nearbyDevices);

  /// Distance in metres per visible endpoint. Only peers with a fresh BLE
  /// RSSI estimate appear here. No entry means the distance is unknown.
  Map<String, double> get peerDistances => Map.unmodifiable(_peerDistances);

  ProximityBand bandFor(String endpointId) =>
      RssiRanging.bandFor(_peerDistances[endpointId]);
  double? smoothedRssiFor(String endpointId) =>
      _ranging.smoothedRssi(bleIdFor(endpointId));
  Set<String> get localFriends => Set.unmodifiable(_localFriends);
  List<String> get privacyLogs => _privacyLogs;
  List<Map<String, dynamic>> get notificationLog => _notificationLog;
  Map<String, int> get appUsageStats => Map.unmodifiable(_appUsageStats);
  Map<String, int> get totalDailyUsage => Map.unmodifiable(_totalDailyUsage);
  bool get notificationEnabled => _notificationEnabled;
  bool get usageEnabled => _usageEnabled;
  double? get lastLat => _lastLat;
  double? get lastLng => _lastLng;
  double get sLoc => _sLoc;
  double get sSoc => _sSoc;
  double get sDig => _sDig;
  double get spatialWeight => _spatialWeight;
  double get socialWeight => _socialWeight;
  double get digitalWeight => _digitalWeight;

  bool isFriend(String bleId) => _localFriends.contains(bleId);

  /// Stable BLE id for a currently-visible endpoint (falls back to endpointId).
  String bleIdFor(String endpointId) =>
      _endpointToBle[endpointId] ?? endpointId;

  /// Server-side info for a peer: {known, display_name, cas}. Null until looked up.
  Map<String, dynamic>? peerInfo(String bleId) => _peerInfo[bleId];

  Map<String, dynamic>? get campus => _campus;
  DateTime? get lastCommunitySync => _lastCommunitySync;
  bool get communityOnline => _communityOnline;
  bool get shareZone => _shareZone;
  bool get communityEnabled => _communityEnabled;

  /// Opt in/out of the community server. Opting out stops all uploads;
  /// local scoring keeps working (contagion just has no peer data).
  Future<void> setCommunityEnabled(bool value) async {
    _communityEnabled = value;
    await prefs.setBool('community_enabled', value);
    _addLog('PRIVACY | Community sync ${value ? "ON" : "OFF"}');
    notifyListeners();
    if (value) unawaited(syncWithCommunity());
  }

  Future<void> setShareZone(bool value) async {
    _shareZone = value;
    await prefs.setBool('share_zone_with_campus', value);
    _addLog('PRIVACY | Zone sharing with campus ${value ? "ON" : "OFF"}');
    notifyListeners();
  }

  // ══════════════════════════════════════════════════════════════════════
  // IDENTITY CREATION (Phase 0 → onboarding)
  // ══════════════════════════════════════════════════════════════════════

  /// Called from onboarding screen after user accepts privacy notice.
  /// Creates a stable UUID-based local identity and generates BLE advertising ID.
  Future<void> createLocalIdentity({String? displayName}) async {
    const uuidGen = Uuid();
    _localId = uuidGen.v4();
    await prefs.setString('local_identity_id', _localId!);

    // Generate BLE advertising ID (short hex, used for P2P proximity)
    final random = Random.secure();
    final values = List<int>.generate(8, (i) => random.nextInt(256));
    _bluetoothId = values
        .map((b) => b.toRadixString(16).padLeft(2, '0'))
        .join();
    await prefs.setString('bluetooth_id', _bluetoothId!);

    if (displayName != null && displayName.isNotEmpty) {
      _displayName = displayName;
      await prefs.setString('user_display_name', displayName);
    }

    _addLog('IDENTITY | Created local UUID identity: $_localId');
    notifyListeners();
    unawaited(syncWithCommunity());
  }

  // ══════════════════════════════════════════════════════════════════════
  // PIN SECURITY (Phase 6)
  // ══════════════════════════════════════════════════════════════════════

  /// Sets security PIN during onboarding. PIN is hashed and stored in SecureStorage.
  Future<bool> setPin(String pin) async {
    if (pin.length < 4) return false;
    await _db.storePin(pin);
    _isPinSet = true;
    _isUnlocked = true; // Just set it → already unlocked
    await prefs.setBool('pin_is_set', true);
    _addLog('SECURITY | PIN set and encryption keys generated');
    notifyListeners();
    return true;
  }

  /// Verifies PIN and unlocks the session.
  Future<bool> verifyPin(String pin) async {
    final ok = await _db.verifyPin(pin);
    if (ok) {
      _isUnlocked = true;
      _addLog('SECURITY | Session unlocked via PIN');
      notifyListeners();
    }
    return ok;
  }

  /// Locks the session (requires PIN re-entry).
  void lockSession() {
    _isUnlocked = false;
    notifyListeners();
  }

  // ══════════════════════════════════════════════════════════════════════
  // ENGINE START
  // ══════════════════════════════════════════════════════════════════════

  /// Called after identity is created and PIN (if required) is verified.
  Future<void> initialize() async {
    if (_localId == null) return;

    // If PIN is set but session not yet unlocked, wait for PIN screen
    if (_isPinSet && !_isUnlocked) {
      notifyListeners();
      return;
    }

    if (Platform.isAndroid) {
      _startNativeTelemetry();
      _listenToEvents();
    }

    await _loadSessionData();
    await _recalculateLocalScore();

    unawaited(syncWithCommunity());
    _syncTimer?.cancel();
    _syncTimer = Timer.periodic(
      const Duration(minutes: 5),
      (_) => syncWithCommunity(),
    );
  }

  // ══════════════════════════════════════════════════════════════════════
  // COMMUNITY SYNC
  // ══════════════════════════════════════════════════════════════════════

  /// Registers (once), publishes the current score, flushes queued
  /// engagements (getting each peer's real CAS back), and refreshes the
  /// campus view. Safe to call any time; no-ops while one is in flight.
  Future<void> syncWithCommunity() async {
    if (_syncing ||
        !_communityEnabled ||
        _localId == null ||
        _bluetoothId == null)
      return;
    _syncing = true;
    try {
      final registered = await _community.ensureRegistered(
        localId: _localId!,
        bluetoothId: _bluetoothId!,
        displayName: _displayName,
      );
      if (!registered) {
        _communityOnline = false;
        return;
      }

      final published = await _community.publishScore(
        cas: _focusScore,
        sLoc: _sLoc,
        sSoc: _sSoc,
        sDig: _sDig,
        zone: _shareZone && _currentZone != null ? _currentZone : null,
      );
      _communityOnline = published;
      if (!published) return;

      final changed = await _flushEngagements();
      if (changed) await _recalculateLocalScore();

      final campus = await _community.fetchCommunity();
      if (campus != null) {
        _campus = campus;
        _lastCommunitySync = DateTime.now();
      }
    } finally {
      _syncing = false;
      notifyListeners();
    }
  }

  /// Returns true if any engagement got a real peer CAS (score must be redone).
  Future<bool> _flushEngagements() async {
    var changed = false;
    for (final row in await _db.getUnsyncedEngagements()) {
      final res = await _community.reportEngagement(
        peerBluetoothId: row['peer_ble_id'] as String,
        durationSeconds: (row['engagement_duration_seconds'] as num).toDouble(),
        endedAt: (row['timestamp'] as num).toDouble(),
      );
      if (res == null) break; // offline: keep the rest queued
      final peerCas = (res['peer_cas'] as num?)?.toDouble();
      await _db.markEngagementSynced(row['id'] as int, peerCas);
      if (peerCas != null) {
        changed = true;
        _addLog(
          'CONTAGION | ${row['peer_ble_id']} CAS ${peerCas.toStringAsFixed(0)} → ${res['effect']}',
        );
      }
    }
    return changed;
  }

  Future<void> _lookupPeer(String bleId) async {
    final info = await _community.lookupPeer(bleId);
    if (info == null) return;
    _peerInfo[bleId] = info;
    notifyListeners();
  }

  /// Erases this device's server-side data (local data is untouched) and
  /// turns community sync off so the next tick doesn't re-register.
  Future<bool> deleteCommunityData() async {
    final ok = await _community.deleteRemoteData();
    if (ok) {
      _communityEnabled = false;
      await prefs.setBool('community_enabled', false);
      _campus = null;
      _communityOnline = false;
      _peerInfo.clear();
      _addLog('PRIVACY | Community data erased from server');
      notifyListeners();
    }
    return ok;
  }

  /// Loads today's tracked data from encrypted DB into memory for UI display.
  Future<void> _loadSessionData() async {
    try {
      final now = DateTime.now();
      final startOfDay =
          DateTime(now.year, now.month, now.day).millisecondsSinceEpoch /
          1000.0;

      // 1. Load session app usage from digital_logs
      final dLogs = await _db.getLogs(
        'digital_logs',
        where: 'timestamp >= ?',
        whereArgs: [startOfDay],
      );
      _appUsageStats.clear();
      for (final log in dLogs) {
        final pkg = log['package_name'] as String?;
        final durationMs = (log['duration_ms'] as num?)?.toInt() ?? 10000;
        if (pkg != null && pkg != 'unknown') {
          _appUsageStats[pkg] =
              (_appUsageStats[pkg] ?? 0) + (durationMs ~/ 1000);
        }
      }

      // Also fetch total usage from OS
      await _refreshAppUsageFromOS();

      // 2. Load notification log for Notification display
      final nLogs = await _db.getLogs('notification_logs', limit: 30);
      _notificationLog.clear();
      for (final n in nLogs) {
        final content = n['content'] as String? ?? 'Notification';
        final ts = ((n['timestamp'] as num) * 1000).toInt();
        _notificationLog.add({
          'package': n['app_category'] ?? 'unknown',
          'title': content.length > 30 ? content.substring(0, 30) : content,
          'text': content,
          'time': DateTime.fromMillisecondsSinceEpoch(ts).toIso8601String(),
          'status': n['response_time_seconds'] != null
              ? 'clicked'
              : 'dismissed',
        });
      }

      // 3. Populate Data tab privacy logs from recent activity
      _privacyLogs.clear();
      // Add app usage entries
      _appUsageStats.forEach((pkg, secs) {
        if (secs > 60) {
          // only show apps used > 1 min
          final mins = secs ~/ 60;
          _privacyLogs.add('[TODAY] USG | $pkg → ${mins}m foreground');
        }
      });
      // Add notification entries
      for (final n in nLogs.take(10)) {
        final ts = ((n['timestamp'] as num) * 1000).toInt();
        final dt = DateTime.fromMillisecondsSinceEpoch(ts);
        final timeStr =
            '${dt.hour.toString().padLeft(2, '0')}:${dt.minute.toString().padLeft(2, '0')}';
        final content = n['content'] as String? ?? '';
        _privacyLogs.add(
          '[$timeStr] NOTIF | ${content.length > 40 ? content.substring(0, 40) : content}',
        );
      }

      // 4. Load proximity data
      final pLogs = await _db.getLogs(
        'proximity_logs',
        limit: 5,
        where: 'timestamp >= ?',
        whereArgs: [startOfDay],
      );
      if (pLogs.isNotEmpty) {
        _nearbyPeers =
            (pLogs.first['nearby_peers_count'] as num?)?.toInt() ?? 0;
        _privacyLogs.add('[TODAY] PROX | $_nearbyPeers peers detected today');
      }

      // 5. Add location data
      final lLogs = await _db.getLogs(
        'location_logs',
        limit: 5,
        where: 'timestamp >= ?',
        whereArgs: [startOfDay],
      );
      for (final l in lLogs) {
        final zone = l['mapped_zone'] as String? ?? 'Unknown';
        final periods = l['periods_count'] as int? ?? 1;
        _privacyLogs.add('[TODAY] LOC | Zone: $zone (${periods} readings)');
      }

      notifyListeners();
    } catch (e) {
      debugPrint('Error loading session data: $e');
    }
  }

  /// Fetches actual app usage from Android UsageStatsManager and populates _appUsageStats.
  Future<void> _refreshAppUsageFromOS() async {
    if (!Platform.isAndroid) return;
    try {
      final dynamic result = await _channel.invokeMethod('getDailyUsage');
      if (result != null && result is Map) {
        _totalDailyUsage.clear();
        result.forEach((key, value) {
          final secs = (value is num) ? value.toInt() : 0;
          if (secs > 0) {
            _totalDailyUsage[key.toString()] = secs;
          }
        });
      }
    } catch (e) {
      debugPrint('Failed to refresh app usage from OS: $e');
    }
  }

